def mostrar_menu():
    print("\nBienvenido a la calculadora de conversiones")
    print("Estas son las conversiones disponibles:\n")
    for i in range(len(menu)):
        print(f"{i}. {menu[i]}")

# Pedir el índice de la conversión
def pedir_indice():
    while True:
        entrada = input("\nIngrese el índice de la conversión: ")

        if entrada.isdigit() and 0 <= int(entrada) < len(menu):
            return int(entrada)
        print(f"Índice inválido. Debe ser un número entre 0 y {len(menu) - 1}.")

# Pedir el valor a convertir (valida que no esté vacío)
def pedir_valor():
    while True:
        valor = input("Ingrese el valor que desea convertir: ").strip()
        if valor != "":
            return valor
        print("Error: Debe ingresar al menos un carácter.")

# Primera conversión: Binario a decimal
def binario_a_decimal(valor):
    suma = 0
    potencia = 0
    largo = len(valor)
    for i in range(largo):
        caracter = valor[largo - 1 - i]
        digito = int(caracter)
        suma = suma + (digito * (2 ** potencia))
        potencia = potencia + 1

    print("El resultado es:", suma)

# Segunda conversión: Hexadecimal a decimal
def hexadecimal_a_decimal(valor):
    suma = 0
    potencia = 0
    largo = len(valor)
    for i in range(largo):
        caracter = valor[largo - 1 - i]
        digito = guia.index(caracter)

        if digito > 15:
            digito = digito - 16

        suma = suma + (digito * (16 ** potencia))
        potencia = potencia + 1

    print("El resultado es:", suma)

# Tercera conversión: Decimal a binario
def decimal_a_binario(valor):
    valor = int(valor)
    if valor == 0:
        resultado = "0"
    else:
        resultado = ""
        while valor > 0:
            residuo = valor % 2
            resultado = str(residuo) + resultado
            valor = valor // 2

    print("El resultado es:", resultado)

# Cuarta conversión: Decimal a hexadecimal
def decimal_a_hexadecimal(valor):
    valor = int(valor)  # ARREGLADO: Se convierte la cadena a entero
    if valor == 0:
        resultado = "0"
    else:
        resultado = ""
        while valor > 0:
            residuo = valor % 16
            letra = guia[residuo]
            resultado = letra + resultado
            valor = valor // 16

    print("El resultado es:", resultado)

# Quinta conversión: Binario a hexadecimal
