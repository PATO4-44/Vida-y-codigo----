"""##  2
# Cálculo de Distancia Euclidiana entre Puntos Cartesianos

Este programa calcula la distancia geométrica en el plano bidimensional entre dos puntos $P_1(x_1, y_1)$ y $P_2(x_2, y_2)$ aplicando la fórmula euclidiana.  
"""

import math

# 1. Función requerida por el ejercicio
def calcular_distancia():
    while True:
        try:
            x1 = float(input("  Coordenada x1: "))
            y1 = float(input("  Coordenada y1: "))
            x2 = float(input("  Coordenada x2: "))
            y2 = float(input("  Coordenada y2: "))
            break
        except ValueError:
            print("  [Error] Por favor, ingrese solo números.\n")

    # Cálculo y respuesta formateada
    distancia = math.sqrt(((x2 - x1) ** 2) + ((y2 - y1) ** 2))
    print(f"  La distancia resultante es: {distancia:,.2f}")



# Pedir la cantidad de veces que se calculará la distancia
